/// Raw font weight primitives for the Dievas typography system. Values match
/// the CSS font weight scale (100 to 900).
abstract final class DievasFontWeightPrimitives {
  /// 100. FontWeight.w100.
  static const int thin = 100;

  /// 200. FontWeight.w200.
  static const int extraLight = 200;

  /// 300. FontWeight.w300.
  static const int light = 300;

  /// 400. FontWeight.w400. Default body weight.
  static const int regular = 400;

  /// 500. FontWeight.w500.
  static const int medium = 500;

  /// 600. FontWeight.w600.
  static const int semiBold = 600;

  /// 700. FontWeight.w700.
  static const int bold = 700;

  /// 800. FontWeight.w800.
  static const int extraBold = 800;

  /// 900. FontWeight.w900.
  static const int black = 900;
}
