/// Raw font size primitives for the Dievas typography system. Values mirror the
/// Moon Design System type ramp; small sizes use role names, sizes above xl2 use
/// `fs<px>` names.
abstract final class DievasFontSizePrimitives {
  /// 6px.
  static const double xs = 6.0;

  /// 8px.
  static const double sm = 8.0;

  /// 9px.
  static const double smPlus = 9.0;

  /// 10px.
  static const double md = 10.0;

  /// 12px.
  static const double mdPlus = 12.0;

  /// 14px. Default body size.
  static const double base = 14.0;

  /// 16px.
  static const double lg = 16.0;

  /// 18px.
  static const double lgPlus = 18.0;

  /// 20px.
  static const double xl = 20.0;

  /// 24px.
  static const double xl2 = 24.0;

  /// 28px.
  static const double fs28 = 28.0;

  /// 32px.
  static const double fs32 = 32.0;

  /// 36px.
  static const double fs36 = 36.0;

  /// 40px.
  static const double fs40 = 40.0;

  /// 48px.
  static const double fs48 = 48.0;

  /// 56px.
  static const double fs56 = 56.0;

  /// 60px.
  static const double fs60 = 60.0;

  /// 64px.
  static const double fs64 = 64.0;

  /// 72px.
  static const double fs72 = 72.0;
}
